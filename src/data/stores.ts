const HOME_LOCALITY = 'Girona';

export function createStaticStoreRepository(stores: readonly Store[]): StoreRepository {
  const bySlug = new Map(stores.map((s) => [s.slug, s]));
  return {
    all: () => stores,
    bySlug: (slug) => bySlug.get(slug),
    byLocality: () => {
      const localities = [...new Set(stores.map((s) => s.address.locality))].sort((a, b) =>
        a === HOME_LOCALITY ? -1 : b === HOME_LOCALITY ? 1 : a.localeCompare(b, 'ca'),
      );
      return new Map(localities.map((loc) => [loc, stores.filter((s) => s.address.locality === loc)]));
    },
  };
}

export const storeRepository = createStaticStoreRepository(STORES);
